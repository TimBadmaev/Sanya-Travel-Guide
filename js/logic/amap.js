// «Как добраться» — маршрут до места во внешнем приложении Amap (AMAP Global,
// D-02, D-12, PRODUCT.md 8.5, разрешение открытого Q-03). Документированный
// URI route-planning механизм: https://lbs.amap.com/api/uri-api/guide/travel/route
// (проверено точечно 2026-09-16; параметр mode — повторно 2026-10-10). Модуль чистый: не знает ни про DOM, ни про
// storage (PRODUCT.md 10.3), как distance.js рядом.
//
// Координатный нюанс (R-05, D-19): у документированного uri.amap.com/navigation
// нет параметра пересчёта системы координат (в отличие от отдельного
// uri.amap.com/marker, где документирован coordinate=gaode|wgs84). Проект
// хранит координаты в WGS-84 — они передаются как есть, без самодельного
// пересчёта в GCJ-02: это осознанный компромисс владельца, а не недосмотр.
// Возможное смещение точки в Китае — уже известный и принятый риск R-05;
// «Показать таксисту» с китайским адресом остаётся точным запасным вариантом
// и существует отдельно от этой кнопки.

// Валидные, отличные от «нулевого острова» координаты — черновики вроде
// bohou-village хранят location: { lat: 0, lng: 0 } как явную заглушку, а не
// реальную точку; loadPlaces()/loadFood() и так скрывают черновики (D-18), но
// проверка остаётся на случай неполных данных у verified-записи.
export function isValidLocation(location) {
  return (
    Boolean(location) &&
    Number.isFinite(location.lat) &&
    Number.isFinite(location.lng) &&
    !(location.lat === 0 && location.lng === 0)
  );
}

// Режимы маршрута, которые приложение предлагает явно (UX-итерация 2026-10).
// Раньше ссылка всегда строила пеший маршрут (mode=walk) — для большинства
// мест каталога, до которых десятки километров, это заведомо неуместно.
// Автоматически режим не выбирается: маршрут начинается от текущей позиции
// телефона (её знает Amap, а не приложение), а точка проживания в настройках
// — ориентир, а не адрес отеля, и мерить по ней «далеко или близко» нельзя.
// Поэтому режим выбирает пользователь (views/route.js); порядок массива —
// порядок кнопок, первый режим совпадает со значением по умолчанию самой
// Amap (mode=car).
export const ROUTE_MODES = [
  { id: "car", label: "🚗 На машине" },
  { id: "walk", label: "🚶 Пешком" },
];
const ROUTE_MODE_IDS = ROUTE_MODES.map((mode) => mode.id);

// to=lon,lat[,name] (долгота, затем широта — формат uri.amap.com/navigation);
// from не задаём — при пустом start Amap на мобильном устройстве сама берёт
// текущую позицию пользователя (документированное поведение). mode — car или
// walk (документированные значения параметра); неизвестный режим не
// подставляется в адрес — берётся первый из ROUTE_MODES. callnative=1 —
// попытка открыть приложение Amap, если оно установлено; страница
// https://uri.amap.com сама остаётся рабочей веб-страницей, если приложения
// нет (официальный H5-запасной вариант, никаких дополнительных проверок
// наличия приложения не требуется). Название кодируется целиком
// (encodeURIComponent): запятая в нём не ломает тройку lon,lat,name, а
// иероглифы и «&» не ломают строку запроса.
export function buildAmapRouteUrl(location, name, mode) {
  const safeMode = ROUTE_MODE_IDS.includes(mode) ? mode : ROUTE_MODE_IDS[0];
  const to = `${location.lng},${location.lat},${encodeURIComponent(name)}`;
  return `https://uri.amap.com/navigation?to=${to}&mode=${safeMode}&callnative=1`;
}
